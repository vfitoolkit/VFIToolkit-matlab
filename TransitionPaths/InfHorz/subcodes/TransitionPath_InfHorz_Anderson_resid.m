function [GEcondns,aprimeReferencePath]=TransitionPath_InfHorz_Anderson_resid(pvec,aprimeReferencePath,uselocalsearch,nPrices, ...
    PricePathNames,PricePathSizeVec,ParamPath,ParamPathNames,ParamPathSizeVec,T,V_final,AgentDist_initial,n_d, ...
    n_a,n_z,n_e,N_a,N_z,N_e,l_d,l_aprime,d_gridvals,aprime_gridvals,a_gridvals,a_grid,z_gridvals,e_gridvals, ...
    ze_gridvals,pi_z,pi_z_sparse,pi_e,ReturnFn,FnsToEvaluateCell,AggVarNames,FnsToEvaluateParamNames, ...
    GeneralEqmEqnsCell,GeneralEqmEqnParamNames,Parameters,DiscountFactorParamNames,ReturnFnParamNames, ...
    use_tminus1price,use_tminus1params,use_tplus1price,use_tminus1AggVars,use_stockvars,tminus1priceNames, ...
    tminus1paramNames,tplus1priceNames,tplus1pricePathkk,tminus1AggVarsNames,stockvarsNames, ...
    stockvarInPricePathNames,vfoptions,simoptions,transpathoptions,itercounter,PolicyIndexesPath,N_probs,II1,II2)
% The residual AndersonAccelerationTPath evaluates, as a TWO-OUTPUT call so that the reference policy
% can be carried in and out. This is a file rather than an anonymous function in
% TransitionPath_InfHorz_Anderson because an anonymous function forwards its body's outputs IN ORDER,
% and what is needed here is outputs 1 and 5 of TransitionPath_InfHorz_singlepathiter with a reshape
% on the first. It holds no logic of its own beyond the four lines below.
%
% ONE FUNCTION SERVES BOTH CLOSURES. uselocalsearch=1 is the restricted residual Anderson iterates
% on; uselocalsearch=0 is the VerifyFn, the unrestricted evaluation that certifies convergence. Both
% must leave a reference behind for the next restricted sweep, which is what localsearchseed does on
% the unrestricted one.
%
% THE FIRST SWEEP OF A SOLVE CANNOT BE RESTRICTED: there is no reference yet, and Step1 refuses
% localsearch=1 with an empty aprimeReferencePath by name. An empty reference therefore forces an
% unrestricted sweep, which is the same rule TransitionPath_InfHorz_shooting follows by making its
% iteration 1 a standard sweep.
if isempty(aprimeReferencePath)
    uselocalsearch=0;
end
vfoptions.localsearch=uselocalsearch;
vfoptions.localsearchseed=1-uselocalsearch;

[GEcondnPath,~,~,~,aprimeReferencePath]=TransitionPath_InfHorz_singlepathiter( ...
    reshape(pvec,T,nPrices),PricePathNames,PricePathSizeVec,ParamPath,ParamPathNames,ParamPathSizeVec,T,V_final, ...
    AgentDist_initial,n_d,n_a,n_z,n_e,N_a,N_z,N_e,l_d,l_aprime,d_gridvals,aprime_gridvals,a_gridvals,a_grid, ...
    z_gridvals,e_gridvals,ze_gridvals,pi_z,pi_z_sparse,pi_e,ReturnFn,FnsToEvaluateCell,AggVarNames, ...
    FnsToEvaluateParamNames,GeneralEqmEqnsCell,GeneralEqmEqnParamNames,Parameters,DiscountFactorParamNames, ...
    ReturnFnParamNames,use_tminus1price,use_tminus1params,use_tplus1price,use_tminus1AggVars,use_stockvars, ...
    tminus1priceNames,tminus1paramNames,tplus1priceNames,tplus1pricePathkk,tminus1AggVarsNames,stockvarsNames, ...
    stockvarInPricePathNames,vfoptions,simoptions,transpathoptions,itercounter,PolicyIndexesPath, ...
    aprimeReferencePath,N_probs,II1,II2);

GEcondns=reshape(GEcondnPath,[],1);

end
